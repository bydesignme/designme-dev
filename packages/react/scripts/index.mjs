// Writes src/index.ts: every component, in the site's order, then the shared pieces.
// usage: node scripts/index.mjs   (from packages/react)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const order = JSON.parse(fs.readFileSync(path.resolve(pkg, '../../r/index.json'), 'utf8')).items.map(i => i.name);
const files = order.flatMap(name => {
  const dir = path.join(pkg, 'src/components', name);
  const tsx = fs.existsSync(dir) ? fs.readdirSync(dir).find(f => /^[A-Z].*\.tsx$/.test(f)) : undefined;
  return tsx ? [`./components/${name}/${tsx.replace(/\.tsx$/, '')}`] : [];
});
fs.writeFileSync(path.join(pkg, 'src/index.ts'), `// Generated by scripts/index.mjs. Everything in one place, for projects that copy the whole folder.
// Each component imports its own styles, so importing a component is all it takes.
${files.map(f => `export * from '${f}';`).join('\n')}
export { Icon, type IconName } from './lib/icons';
export { Brand, type BrandName } from './lib/brands';
export { Flag, type FlagCode } from './lib/flags';
export { Think, Spin, Radar, Pulse, Bars, Dot, Swap, Fold, Seg, Tip, Avatar, SourceChip, enter, type Source, type SourceKind } from './lib/motion';
export { usePopover, type PopoverOptions } from './lib/popover';
export { useControllable, useCopied, useTween, useSeconds, useReducedMotion } from './lib/hooks';
`);
console.log(`index.ts exports ${files.length} components`);
